def load_data(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

def matches_selected_name(title):
    return title in person_names

########################################################################################################################################################
########################################################################################################################################################

person_names = set(PERSON_NAMES)

data = load_data(INPUT_FILE)

print(f"Total number of records: {len(data)}")

selected_dataset = [
    {"title": example["title"],
     "full_text": example["full_text"],
     "question": example["question"],
     "answer": example["answer"],
    } for example in data if matches_selected_name(example.get("title", ""))
]

with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
    json.dump(selected_dataset, f, ensure_ascii=False, indent=2)

matched_titles = sorted({example["title"] for example in selected_dataset})

missing_names = [name for name in PERSON_NAMES if name not in matched_titles]

print(f"Total records saved: {len(selected_dataset)}")
print(f"Unique matched titles saved: {len(matched_titles)}")

if missing_names:
    print("\nNames not found in the dataset:")
    for name in missing_names:
        print(name)
        
